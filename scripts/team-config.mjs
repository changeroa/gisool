import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../worker/", import.meta.url);
const config = JSON.parse(await readFile(new URL("wrangler.team.jsonc", root), "utf8"));
const id = process.env.GISUL_OAUTH_KV_ID;
if (!id || !/^[a-f0-9]{32}$/.test(id)) throw new Error("GISUL_OAUTH_KV_ID must identify the team OAuth KV namespace");
const account = process.env.CLOUDFLARE_ACCOUNT_ID;
if (!account || !/^[a-f0-9]{32}$/.test(account)) throw new Error("CLOUDFLARE_ACCOUNT_ID is required");
const publicUrl = process.env.GISUL_PUBLIC_URL;
let origin;
try { origin = new URL(publicUrl); } catch { throw new Error("GISUL_PUBLIC_URL must be a real HTTPS origin"); }
if (origin.protocol !== "https:" || origin.username || origin.password || origin.search || origin.hash || origin.pathname !== "/" || origin.port || origin.hostname.endsWith("example.invalid") || publicUrl !== origin.origin) throw new Error("GISUL_PUBLIC_URL must be a real HTTPS origin without credentials, path, query, fragment or port");
const organization = process.env.GISUL_GITHUB_ORG;
const repository = process.env.GISUL_SKILLS_REPOSITORY;
if (!organization || !/^[A-Za-z0-9-]+$/.test(organization)) throw new Error("GISUL_GITHUB_ORG is required");
if (!repository || !/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository)) throw new Error("GISUL_SKILLS_REPOSITORY must be owner/repository");
const bucket = process.env.GISUL_SKILLS_BUCKET;
if (!bucket) throw new Error("GISUL_SKILLS_BUCKET is required");
config.name = process.env.GISUL_WORKER_NAME || "gisul-team";
config.routes = [{ pattern: origin.hostname, custom_domain: true }];
config.r2_buckets[0].bucket_name = bucket;
config.vars.GISUL_PUBLIC_URL = publicUrl;
config.vars.GISUL_GITHUB_ORG = organization;
config.vars.GISUL_SKILLS_REPOSITORY = repository;
config.account_id = account;
config.kv_namespaces = [{ binding: "OAUTH_KV", id }];
config.vars.GISUL_SERVER_VERSION = process.env.GISUL_SERVER_VERSION ?? process.env.GITHUB_SHA ?? "development";
config.vars.GITHUB_CLIENT_ID = process.env.GITHUB_CLIENT_ID ?? "";
if (!config.vars.GITHUB_CLIENT_ID) throw new Error("GITHUB_CLIENT_ID must be configured before deployment");
await writeFile(new URL("wrangler.team.generated.json", root), JSON.stringify(config, null, 2) + "\n");
console.log("Generated Worker configuration (nonsecret values only)");
